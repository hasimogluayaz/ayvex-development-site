const reveals = document.querySelectorAll(".reveal");
const langToggle = document.querySelector("#langToggle");
const translatable = document.querySelectorAll("[data-i18n]");
const pageTitle = document.querySelector("title");
const pageMetaDescription = document.querySelector('meta[name="description"]');

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.16 }
);

reveals.forEach((element) => observer.observe(element));

function applyLanguage(lang) {
  const dictionary = translations[lang];
  if (!dictionary) return;

  translatable.forEach((element) => {
    const key = element.dataset.i18n;
    const value = dictionary[key];
    if (!value) return;
    element.textContent = value;
  });

  if (lang === "tr") {
    document.documentElement.lang = "tr";
    pageTitle.textContent = "AyveX Development | Web, App, Dijital Urunler";
    pageMetaDescription.setAttribute(
      "content",
      "AyveX Development modern web siteleri ve web uygulamalari gelistirir, urunleri fikirden yayina tasir."
    );
    langToggle.textContent = "TR";
  } else {
    document.documentElement.lang = "en";
    pageTitle.textContent = "AyveX Development | Web, App, Digital Products";
    pageMetaDescription.setAttribute(
      "content",
      "AyveX Development develops modern websites and web applications and launches products from idea to release."
    );
    langToggle.textContent = "EN";
  }
}

function setLanguage(lang) {
  localStorage.setItem("ayvex-language", lang);
  applyLanguage(lang);
}

const storedLanguage = localStorage.getItem("ayvex-language");
const initialLanguage = storedLanguage === "en" ? "en" : "tr";
setLanguage(initialLanguage);

langToggle.addEventListener("click", () => {
  const currentLang = localStorage.getItem("ayvex-language") || "tr";
  setLanguage(currentLang === "tr" ? "en" : "tr");
});
